    location: str | None

    # Q417/Q428: for a related part this is the PARENT's cutlist number. The
    # related part never holds one itself.
    item_id: int | None
    item_number: int | None
    cutlist_no: str | None

    category: str
    description: str
    product_code: str | None
    product_description: str | None

    quantity: Decimal | None
    unit_of_measure: str | None
    unit_cost: Decimal | None
    total_amount: Decimal | None
    currency: str | None

    required_date: date | None
    date_ordered: date | None
    due_date: date | None

    notes: str | None
    internal_comments: str | None
    attributes: dict

    created_at: datetime
    updated_at: datetime
    # §L Q511/Q512 — field-level optimistic concurrency.
    field_versions: dict[str, int] = {}

    # The cost centre an Approved order commits its total against (optional, Q563).
    cost_center_id: int | None = None
    cost_center_code: str | None = None
    cost_center_name: str | None = None
    # Why the order was rejected; set only while its status is Rejected (0056).
    rejection_note: str | None = None

    # The old Orderbook's columns and HOME tab. `gst_amount` / `grand_total` are generated by the
    # database from `total_amount` and the two GST flags (0002).
    requester_id: int | None = None
    requester_name: str | None = None
    requested_date: date | None = None
    arrived_date: date | None = None
    stock_tracked: bool | None = None
    gst_applicable: bool | None = None
    gst_included_in_price: bool | None = None
    gst_amount: Decimal | None = None
    grand_total: Decimal | None = None
    line_item_comments: str | None = None
    changelog: str | None = None
    product_website: str | None = None
    # The PO document this order is on (0059), if any: its running number comes from `po_document`.
    po_document_id: int | None = None
    po_no: int | None = None
    has_attachment: bool = False
    # ADMIN tab: when an order was cancelled, by whom and why (0064), and the Delivery log's final
    # "Received by" (the final date is `arrived_date`).
    cancelled_at: datetime | None = None
    cancelled_by_name: str | None = None
    cancel_reason: str | None = None
    received_by: str | None = None
    has_image: bool = False

    @computed_field  # type: ignore[prop-decorator]
    @property
    def locked(self) -> bool:
        """True when the order is in a frozen status (`FROZEN_STATUSES`): read-only
        except for `status`. The server is the source of truth for this, so the web
        decides what to render from this flag instead of keeping its own copy."""
        return self.status in FROZEN_STATUSES


